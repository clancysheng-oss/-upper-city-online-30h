export function novelEpilogue(state){
 const parts=[institutionalEpilogues[state.ending]||'黎明只照亮了今天。尚未确认的罪责、赔偿与去向仍被写在公开清单上，没有因英雄离城而自动结案。'];
 const decisions=state.narrative?.decisions||{};
 if(decisions['5']?.index===1)parts.push('穆雷把匿名保护名单交回工人推选的保管者。他想在名册末尾加一句“我们都是为了活下去”，保管者划去了“都是”：每个人做过什么，还要分开查。');
 if(decisions['7']?.index===2)parts.push('报社留下三份遗言的并列版。一位读者要求删掉埃弗认罪的那封，因为它让整个故事“不像英雄救人”；莉缇把这封要求也收入来信栏。');
 if(decisions['19']?.index===1)parts.push('埃弗在保护下准备作证。他问能否把孩子的名字从新闻中拿掉，莉缇同意；他再问能否也拿掉自己的付款记录，她没有回答，而是把原件放到桌上。');
 if(decisions['23']?.index===1)parts.push('梅瑞让获救的孩子给缺页画了一张新封皮，封面写“这里曾经缺失”。她不让新画冒充旧档案，也不愿为了书页让孩子再回一次火场。');
 if((state.narrative?.stances?.threat||0)>=(state.narrative?.stances?.care||0)+3)parts.push('有人承认你们救过这座城，却拒绝再独自与你们谈话。新约需要的同意不是沉默；罗温把那几次威胁原样记下，等受影响者说明它们留下了什么。');
 return parts;
}
